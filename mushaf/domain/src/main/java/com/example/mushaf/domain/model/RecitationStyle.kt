package com.example.mushaf.domain.model

/**
 * The style of Quranic recitation.
 */
enum class RecitationStyle {
    /** Standard clear reading, standard pace */
    MURATTAL,
    
    /** Slower, melodic reading focusing on tajweed rules */
    MUJAWWAD,
    
    /** Teacher-student call and response style */
    MUALLIM
}
